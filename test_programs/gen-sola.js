// Writes sola.fxc, a SOLA pitch shifter for the FXCore, and sola.fxl, the
// same shifter as the library subroutine @sola.shifter(in, pitch, out, mbase).
//   node test_programs/gen-sola.js
//
// The assembler has no macros, so the two unrolled loops (the near-window
// copy and the correlation) are emitted from here.  Everything else is
// written out once, below, and the numbers come from the same constants.
//
// The design is fv-emu's src/sola.c (see docs/sola-shifter-notes.md there,
// "On the FXCore"): a tap walks a delay line at a constant rate, and before
// it reaches the end of its excursion a second tap is placed where the
// signal best matches, then faded in.  The match is a cross-correlation
// searched one lag per sample, on windows read every fourth sample.

const fs = require('fs');
const path = require('path');

const R = 200;              // search reach, ± samples
const M = 100;              // window points, one per 4 samples (L = 400)
const H = 2 * R + 4;        // ticks from request to splice: one lag per tick
const C = 256;              // crossfade length (must be a power of two)
const E = 1024;             // excursion between the two splice points
const N = H + 32;           // near edge, samples of delay
const F = N + E;            // far edge
const CB = N - H + 1;       // near window's first read, at the request
const PBASE = F - H + R + 2;// far window's first read, at the search's lags
const CSH = 31 - Math.log2(C);
const RING = 2048;

if (PBASE + 4 * M >= RING) throw new Error('ring too small');
// The near window is read where it sits, not copied: by the end of the
// search it has drifted H ticks deeper, and it must still be in the ring.
if (CB + H + 4 * M >= RING) throw new Error('ring too small for the near window');

// Persistent state: in sola.fxc it stays in core registers; in the library
// it lives in MREGs after the window and status words and is loaded and
// stored around the body, so the subroutine can use r0..r15 as scratch.
const STATE = ['d_a', 'd_b', 'fc', 'cd', 'sj', 'e0', 'e1', 'e2', 'e3'];
const SBASE = 7;
// sola.fxc's semitone table: Q16 pitch ratios for -12..+12 at MR7..MR31.
const TBASE = 7, SEMIS = 12;
const MREGS = SBASE + STATE.length;
const REGS = ['dry', 'ratio', 'step', 'd_a', 'd_b', 'fc', 'cd', 'sj',
    'e0', 'e1', 'e2', 'e3', 't', 'u', 'v', 'w'];

// lib: false writes sola.fxc, true the body of @sola.shifter.
function build(lib) {
const L = [];
const emit = (s = '') => L.push(s);
const mr = k => lib ? `mbase+${k}` : `mr${k}`;

if (!lib) {
emit(`; sola.fxc - SOLA pitch shifter, one octave down to one octave up.`);
emit(`; Generated by gen-sola.js; edit that, not this.`);
emit(`;`);
emit(`; #POT0 Pitch`);
emit(`; #POT1 Mix`);
emit(`; #SW0 Free pitch`);
emit(`; #USER0 Snap`);
emit(`;`);
emit(`; POT0_SMTH  pitch, -1 octave at 0, unity at the centre, +1 octave at 1`);
emit(`; POT1_SMTH  mix, dry to wet`);
emit(`; SW0        off: the pitch snaps to semitones, from a table at`);
emit(`;            MR${TBASE}..MR${TBASE + 2 * SEMIS}; on: the pot sets it freely.  USER0 lit when snapping`);
emit(`;`);
emit(`; A tap walks a ${E}-sample stretch of the delay line at (1 - ratio) samples`);
emit(`; per sample, so what it reads is the input resampled.  ${H} ticks before`);
emit(`; it reaches an end the search starts: one lag per tick, the near window`);
emit(`; (every fourth of ${4 * M} samples, ${CB} deep at the request) is correlated`);
emit(`; against the far window as the delay line drifts past, lags -${R}..+${R}.`);
emit(`; Both are read where they sit in the delay line; the near window is`);
emit(`; followed with a pointer as it drifts, so nothing is copied out.`);
emit(`; At the splice a second tap starts at the other end, offset by the best`);
emit(`; lag, and fades in over ${C} samples.  Correlation and window energy are`);
emit(`; scored as log2 c - log2 e / 2, ties going to the nominal lag.`);
emit(`;`);
emit(`; MR0  best score   MR1  best lag   MR2  step at the request`);
emit(`; MR3  splices     MR4  missed     MR5  searches   MR6  last lag`);
emit(`; MR${TBASE}..MR${TBASE + 2 * SEMIS}  pitch ratio for -${SEMIS}..+${SEMIS} semitones, Q16`);
emit();
emit(`.rn   dry   r0`);
emit(`.rn   ratio r1        ; Q16`);
emit(`.rn   step  r2        ; Q16, 1 - ratio: the tap's change of delay per tick`);
emit(`.rn   d_a   r3        ; live tap's delay, 16.16`);
emit(`.rn   d_b   r4        ; fading-in tap's delay, 16.16`);
emit(`.rn   fc    r5        ; fade count, -1 when not fading`);
emit(`.rn   cd    r6        ; ticks to the splice, 0 when none is due`);
emit(`.rn   sj    r7        ; search index 0..${2 * R}, -1 when idle`);
emit(`.rn   e0    r8        ; far window energy, this tick`);
emit(`.rn   e1    r9        ;   and the three before it`);
emit(`.rn   e2    r10`);
emit(`.rn   e3    r11`);
emit(`.rn   t     r12`);
emit(`.rn   u     r13`);
emit(`.rn   v     r14`);
emit(`.rn   w     r15`);
emit();
}
emit(`.mem  ring  ${RING}`);
if (!lib) {
    emit();
    emit(`; the semitone table: 2^(k/12) in Q16, 65536 = unity`);
    for (let k = -SEMIS; k <= SEMIS; k++) {
        const q = Math.round(65536 * 2 ** (k / 12));
        emit(`.mreg mr${TBASE + k + SEMIS}`.padEnd(12) + `${q}`.padEnd(8) +
            `; ${k > 0 ? '+' : ''}${k}`);
    }
}
emit();
emit(`; ---- input`);
emit(lib ? `cpy_cm   dry, in` : `cpy_cs   dry, in0`);
emit(`wrdel    ring, dry`);
emit();
if (lib) {
    emit(`; ---- state`);
    STATE.forEach((r, i) => emit(`cpy_cm   ${r}, ${mr(SBASE + i)}`));
    emit();
}
emit(`; ---- first sample: seat the tap mid-excursion, nothing fading or due`);
emit(`cpy_cs   t, samplecnt`);
emit(`jnz      t, inited`);
emit(`wrdld    d_a, ${N + E / 2}`);
emit(`xor      acc32, acc32`);
emit(`addi     acc32, -1`);
emit(`cpy_cc   fc, acc32`);
emit(`cpy_cc   sj, acc32`);
emit(`inited:`);
emit();
if (!lib) {
    emit(`; ---- pitch, snapped: the pot cut into ${2 * SEMIS + 1} equal slices, one per semitone`);
    emit(`cpy_cs   t, pot0_smth`);
    emit(`cpy_cs   u, switch`);
    emit(`andi     u, sw0db            ; 1 while SW0 is off`);
    emit(`set      user0|0, acc32`);
    emit(`jz       acc32, free_pitch`);
    emit(`multri   t, ${2 * SEMIS + 1}/32            ; ${2 * SEMIS + 1}p / 32, so each slice is 1/32 = 2^26`);
    emit(`sr       acc32, 26           ; floor(${2 * SEMIS + 1}p) = k + ${SEMIS}, 0..${2 * SEMIS}`);
    emit(`addi     acc32, ${TBASE}`);
    emit(`cpy_cmx  ratio, acc32`);
    emit(`jmp      have_ratio`);
    emit();
    emit(`; ---- pitch, free: ratio = 2^(2p - 1), by way of 2^(2p - 2) = ratio / 2`);
    emit(`free_pitch:`);
} else {
    emit(`; ---- pitch: ratio = 2^(2p - 1), by way of 2^(2p - 2) = ratio / 2`);
    emit(`cpy_cm   t, pitch`);
}
emit(`sra      t, 4                ; 2p in S5.26`);
emit(`addsi    acc32, -0.0625      ; - 2.0`);
emit(`addi     acc32, -1           ; stays negative at p = 1`);
emit(`exp2     acc32               ; ratio / 2, S.31`);
emit(`sra      acc32, 14           ; ratio, Q16`);
emit(`cpy_cc   ratio, acc32`);
if (!lib) emit(`have_ratio:`);
emit(`wrdld    step, 1`);
emit(`sub      step, ratio`);
emit(`cpy_cc   step, acc32`);
emit();
emit(`; ---- far window energy, a running sum that drifts with the delay line`);
emit(`rddel    t, ring+${PBASE}`);
emit(`multrr   t, t`);
emit(`sra      acc32, 7`);
emit(`cpy_cc   u, acc32`);
emit(`rddel    t, ring+${PBASE + 4 * M}`);
emit(`multrr   t, t`);
emit(`sra      acc32, 7`);
emit(`sub      u, acc32`);
emit(`add      acc32, e3           ; the sum four ticks ago, plus the new point, less the old`);
emit(`cpy_cc   e3, e2`);
emit(`cpy_cc   e2, e1`);
emit(`cpy_cc   e1, e0`);
emit(`cpy_cc   e0, acc32`);
emit();
emit(`; ---- the splice, when the countdown runs out`);
emit(`jz       cd, no_splice`);
emit(`addi     cd, -1`);
emit(`cpy_cc   cd, acc32`);
emit(`jnz      cd, no_splice`);
emit(`cpy_cm   v, ${mr(1)}          ; the best lag`);
emit(`jneg     sj, answered`);
emit(`xor      acc32, acc32        ; the search is still running: take the nominal lag`);
emit(`cpy_cc   v, acc32`);
emit(`addi     acc32, -1`);
emit(`cpy_cc   sj, acc32`);
emit(`cpy_cm   t, ${mr(4)}`);
emit(`addi     t, 1`);
emit(`cpy_mc   ${mr(4)}, acc32`);
emit(`answered:`);
emit(`cpy_mc   ${mr(6)}, v`);
emit(`cpy_cm   t, ${mr(2)}`);
emit(`jneg     t, splice_up`);
emit(`addi     v, ${N}               ; down: the new tap starts at the near edge`);
emit(`jmp      seated`);
emit(`splice_up:`);
emit(`neg      v`);
emit(`addi     acc32, ${F}           ; up: at the far edge`);
emit(`seated:`);
emit(`sl       acc32, 16`);
emit(`cpy_cc   d_b, acc32`);
emit(`xor      acc32, acc32`);
emit(`cpy_cc   fc, acc32`);
emit(`cpy_cm   t, ${mr(3)}`);
emit(`addi     t, 1`);
emit(`cpy_mc   ${mr(3)}, acc32`);
emit(`no_splice:`);
emit();
emit(`; ---- the search: lag sj - ${R}, the far window read where it has drifted to`);
emit(`jneg     sj, no_search`);
emit(`addi     sj, ring+${CB + 1}       ; the near window, ${CB} deep at the request, has drifted sj + 1`);
emit(`cpy_cc   w, acc32`);
emit(`clracc64`);
for (let m = 0; m < M; m++) {
    emit(`rddelx   t, w`);
    if (m < M - 1) {
        emit(`addi     w, 4`);
        emit(`cpy_cc   w, acc32`);
    }
    emit(`sra      t, 7                ; 1/128 keeps the sum in range`);
    emit(`macrd    acc32, ring+${PBASE + 4 * m}`);
}
emit(`rdacc64u t                   ; c`);
emit(`jneg     t, next_lag         ; no splice on an anti-correlation`);
emit(`jz       t, next_lag`);
emit(`log2     t`);
emit(`cpy_cc   u, acc32`);
emit(`log2     e0`);
emit(`sra      acc32, 1`);
emit(`sub      u, acc32            ; score = log2 c - log2 e / 2`);
emit(`cpy_cc   u, acc32`);
emit(`cpy_cm   t, ${mr(0)}`);
emit(`sub      u, t                ; against the best so far`);
emit(`cpy_cc   v, acc32`);
emit(`addi     sj, -${R + 1}`);
emit(`jneg     acc32, tie_near     ; a lag past the nominal must beat it outright`);
emit(`addi     v, -1`);
emit(`cpy_cc   v, acc32`);
emit(`tie_near:`);
emit(`jneg     v, next_lag`);
emit(`cpy_mc   ${mr(0)}, u`);
emit(`addi     sj, -${R}`);
emit(`cpy_mc   ${mr(1)}, acc32`);
emit(`next_lag:`);
emit(`addi     sj, 1`);
emit(`cpy_cc   sj, acc32`);
emit(`addi     sj, -${2 * R + 1}`);
emit(`jneg     acc32, no_search`);
emit(`xor      acc32, acc32`);
emit(`addi     acc32, -1`);
emit(`cpy_cc   sj, acc32           ; all lags seen`);
emit(`no_search:`);
emit();
emit(`; ---- the request: when the tap will reach its edge in ${H} ticks`);
emit(`jnz      cd, no_req`);
emit(`jgez     fc, no_req`);
emit(`jz       step, no_req`);
emit(`cpy_cc   t, step`);
emit(`jgez     step, step_pos`);
emit(`neg      step`);
emit(`cpy_cc   t, acc32`);
emit(`step_pos:`);
emit(`sl       t, 14`);
emit(`cpy_cc   t, acc32`);
emit(`wrdld    u, ${H * 32}         ; ${H} * 32`);
emit(`multrr   t, u`);
emit(`sra      acc32, 4`);
emit(`cpy_cc   u, acc32            ; lead = |step| * ${H}, 16.16`);
emit(`jneg     step, rem_up`);
emit(`wrdld    t, ${F}`);
emit(`sub      t, d_a              ; down: the far edge is ahead`);
emit(`jmp      rem_done`);
emit(`rem_up:`);
emit(`wrdld    t, ${N}`);
emit(`sub      d_a, t              ; up: the near edge`);
emit(`rem_done:`);
emit(`cpy_cc   v, acc32            ; remaining`);
emit(`jneg     v, past_edge`);
emit(`sub      u, v`);
emit(`jneg     acc32, no_req`);
emit(`xor      acc32, acc32`);
emit(`addi     acc32, ${H}`);
emit(`cpy_cc   cd, acc32`);
emit(`cpy_mc   ${mr(2)}, step`);
emit(`xor      acc32, acc32`);
emit(`cpy_cc   sj, acc32           ; the search starts next tick`);
emit(`cpy_mc   ${mr(1)}, acc32`);
emit(`wrdld    t, 0x8000`);
emit(`cpy_mc   ${mr(0)}, t            ; best score = -inf`);
emit(`cpy_cm   t, ${mr(5)}`);
emit(`addi     t, 1`);
emit(`cpy_mc   ${mr(5)}, acc32`);
emit(`jmp      no_req`);
emit(`past_edge:`);
emit(`; the tap is already past the edge it is walking to (the pitch changed`);
emit(`; mid-grain): splice next tick at the nominal lag, unsearched`);
emit(`xor      acc32, acc32`);
emit(`addi     acc32, 1`);
emit(`cpy_cc   cd, acc32`);
emit(`cpy_mc   ${mr(2)}, step`);
emit(`xor      acc32, acc32`);
emit(`cpy_mc   ${mr(1)}, acc32`);
emit(`no_req:`);
emit();
emit(`; ---- the taps`);
emit(`interp   d_a, ring`);
emit(`cpy_cc   t, acc32            ; a`);
emit(`jneg     fc, one_tap`);
emit(`interp   d_b, ring`);
emit(`sub      acc32, t            ; b - a`);
emit(`cpy_cc   u, acc32`);
emit(`sl       fc, ${CSH}               ; fc / ${C}, S.31`);
emit(`multrr   u, acc32`);
emit(`adds     acc32, t            ; a + (b - a) * fade`);
emit(`cpy_cc   t, acc32`);
emit(`one_tap:`);
emit();
emit(`; ---- advance the taps; the fade done, the new tap is the tap`);
emit(`add      d_a, step`);
emit(`cpy_cc   d_a, acc32`);
emit(`jneg     fc, advanced`);
emit(`add      d_b, step`);
emit(`cpy_cc   d_b, acc32`);
emit(`addi     fc, 1`);
emit(`cpy_cc   fc, acc32`);
emit(`addi     fc, -${C}`);
emit(`jneg     acc32, advanced`);
emit(`cpy_cc   d_a, d_b`);
emit(`xor      acc32, acc32`);
emit(`addi     acc32, -1`);
emit(`cpy_cc   fc, acc32`);
emit(`advanced:`);
emit();
if (lib) {
    emit(`; ---- state, and the wet signal out`);
    STATE.forEach((r, i) => emit(`cpy_mc   ${mr(SBASE + i)}, ${r}`));
    emit(`cpy_mc   out, t`);
} else {
    emit(`; ---- mix`);
    emit(`cpy_cs   u, pot1_smth`);
    emit(`subs     t, dry              ; wet - dry`);
    emit(`multrr   acc32, u`);
    emit(`adds     acc32, dry`);
    emit(`cpy_sc   out0, acc32`);
    emit(`cpy_sc   out1, acc32`);
    emit();
}
return L;
}

const fxc = path.join(__dirname, 'sola.fxc');
const prog = build(false);
fs.writeFileSync(fxc, prog.join('\n'));
console.log(`wrote ${fxc}: ${prog.length} lines`);

// The library. Its code names registers outright rather than by .rn, so it
// cannot collide with the aliases of the program that calls it; only the
// instruction part of a line is rewritten, never its comment.
const regOf = new Map(REGS.map((r, i) => [r, 'r' + i]));
const raw = build(true).map(line => {
    const semi = line.indexOf(';');
    const code = semi < 0 ? line : line.substring(0, semi);
    const note = semi < 0 ? '' : line.substring(semi);
    return code.replace(/\b[a-z_][a-z0-9_]*\b/g, w => regOf.get(w) || w) + note;
});
const esc = t => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const param = (name, side, type, desc) =>
    `\t\t<param>\n\t\t\t<name>${name}</name>\n` + (side ? `\t\t\t<side>${side}</side>\n` : '') +
    `\t\t\t<type>${type}</type>\n\t\t\t<desc>${esc(desc)}</desc>\n\t\t</param>`;
const fxl = [
    `<library>`,
    `\t<name>sola</name>`,
    `\t<desc>SOLA pitch shifter, one octave down to one octave up. Generated by gen-sola.js; edit that, not this.</desc>`,
    `\t<lib_color>0, 128, 160</lib_color>`,
    `\t<lib_text_color>255,255,255</lib_text_color>`,
    `\t<sub>`,
    `\t\t<name>shifter</name>`,
    `\t\t<desc>${esc(`Pitch shifts in by -1 to +1 octave and writes the wet signal to out; ` +
        `mix it with the dry signal outside. Uses ${MREGS} MREGs from mbase up ` +
        `(mbase+0..6 search and status, +${SBASE}..${MREGS - 1} state), ` +
        `${RING} samples of delay memory and all of r0..r15 as scratch.`)}</desc>`,
    param('in', 'L', 'MREG', 'MREG holding the signal to shift'),
    param('pitch', 'L', 'MREG', 'MREG holding the pitch, 0 = -1 octave, 0.5 = unity, 1 = +1 octave'),
    param('out', 'R', 'MREG', 'MREG to receive the shifted (wet) signal'),
    param('mbase', '', 'MREG', `First of the ${MREGS} MREGs the shifter keeps its state in, e.g. mr0`),
    `\t\t<code>`,
    ...raw.map(l => l ? '\t\t\t' + l : ''),
    `\t\t</code>`,
    `\t</sub>`,
    `</library>`,
    ''
];
const fxlPath = path.join(__dirname, 'sola.fxl');
fs.writeFileSync(fxlPath, fxl.join('\n'));
console.log(`wrote ${fxlPath}: ${raw.length} lines of code`);
